from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path


# Result families that existed before the 2026-08-09 repair work. Tests that
# exercise whole-tree analysis build their input from this fixed list rather
# than from a live scan of results/raw: the sensitivity report emits a coverage
# row only when a stratum is *missing*, so simply adding a new benchmark run to
# the repository could delete an expected line and fail an unrelated test. That
# happened once, when a sweep introduced the first rows reporting divergences.
_FIXTURE_FAMILIES = (
    "funnel_ablation",
    "chain_scaling",
    "dimension_scaling",
    "eight_schools",
    "gp",
    "hier_logistic",
    "stoch_vol",
    "long_trace",
    "trace_qa",
)


def _build_raw_fixture(repo_root: Path, destination: Path) -> Path:
    """Copy a fixed subset of raw results so whole-tree tests are deterministic."""
    source_root = repo_root / "results" / "raw"
    destination.mkdir(parents=True, exist_ok=True)
    for family in _FIXTURE_FAMILIES:
        family_dir = source_root / family
        if family_dir.is_dir():
            shutil.copytree(family_dir, destination / family, dirs_exist_ok=True)
    return destination


def test_report_generates_latex_outputs_from_tiny_ablation(tmp_path: Path) -> None:
    repo_root = Path(__file__).resolve().parents[1]
    out_dir = tmp_path / "latex"

    env = os.environ.copy()
    src_path = str(repo_root / "src")
    env["PYTHONPATH"] = src_path + os.pathsep + env.get("PYTHONPATH", "")

    completed = subprocess.run(
        [
            sys.executable,
            "-m",
            "abnuts.analysis.report",
            "--input",
            str(repo_root / "results" / "raw" / "funnel_ablation" / "tiny"),
            "--out",
            str(out_dir),
        ],
        check=True,
        cwd=repo_root,
        env=env,
        text=True,
        capture_output=True,
    )

    table = out_dir / "tables" / "table_bucket_ablation.tex"
    figure = out_dir / "figures" / "fig_speedup_vs_bucket_size.tex"
    macros = out_dir / "macros" / "result_macros.tex"

    assert table.exists()
    assert figure.exists()
    assert macros.exists()
    assert "Wrote LaTeX table" in completed.stdout

    table_text = table.read_text(encoding="utf-8")
    figure_text = figure.read_text(encoding="utf-8")
    macros_text = macros.read_text(encoding="utf-8")

    assert "% Generated by: python -m abnuts.analysis.report" in table_text
    assert "% Source result file:" in table_text
    assert "\\begin{table}" in table_text
    assert "\\begin{tabular}" in table_text
    assert "history" in table_text

    assert "% Source result file:" in figure_text
    assert "\\begin{tikzpicture}" in figure_text
    assert "\\begin{axis}" in figure_text
    assert "\\addplot+" in figure_text

    assert "% Source result file:" in macros_text
    assert "\\newcommand{\\BestWarmSpeedup}" in macros_text
    assert "\\newcommand{\\BestWarmSpeedupConfig}" in macros_text


