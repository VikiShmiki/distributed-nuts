def test_report_generates_aggregate_bundle_from_raw_tree(tmp_path: Path) -> None:
    repo_root = Path(__file__).resolve().parents[1]
    out_dir = tmp_path / "latex" / "all"

    env = os.environ.copy()
    src_path = str(repo_root / "src")
    env["PYTHONPATH"] = src_path + os.pathsep + env.get("PYTHONPATH", "")

    completed = subprocess.run(
        [
            sys.executable,
            "-m",
            "abnuts.analysis.report",
            "--input",
            str(repo_root / "results" / "raw"),
            "--out",
            str(out_dir),
            "--allow-missing",
        ],
        check=True,
        cwd=repo_root,
        env=env,
        text=True,
        capture_output=True,
    )

    processed_dir = tmp_path / "processed" / "all"
    summary = out_dir / "results_summary.tex"
    manifest = out_dir / "manifest.json"

    expected_latex = [
        out_dir / "tables" / "table_bucket_ablation.tex",
        out_dir / "tables" / "table_chain_scaling.tex",
        out_dir / "tables" / "table_dimension_scaling.tex",
        out_dir / "tables" / "table_oracle_gap.tex",
        out_dir / "tables" / "table_diagnostics.tex",
        out_dir / "tables" / "table_runtime_breakdown.tex",
        out_dir / "figures" / "fig_speedup_vs_bucket_size.tex",
        out_dir / "figures" / "fig_chain_scaling.tex",
        out_dir / "figures" / "fig_dimension_scaling.tex",
        out_dir / "figures" / "fig_oracle_gap_waterfall.tex",
        out_dir / "figures" / "fig_predictor_calibration.tex",
        out_dir / "figures" / "fig_padding_heatmap.tex",
        out_dir / "figures" / "fig_speedup_vs_heterogeneity.tex",
        out_dir / "figures" / "fig_runtime_breakdown.tex",
        out_dir / "figures" / "fig_sbc_rank_histogram.tex",
        out_dir / "macros" / "result_macros.tex",
        summary,
    ]
    for path in expected_latex:
        assert path.exists(), path

    assert manifest.exists()
    assert (processed_dir / "all_summary.csv").exists()
    assert (processed_dir / "equivalence_checks.csv").exists()
    assert (processed_dir / "missing_results.csv").exists()

    summary_text = summary.read_text(encoding="utf-8")
    macros_text = (out_dir / "macros" / "result_macros.tex").read_text(encoding="utf-8")
    manifest_text = manifest.read_text(encoding="utf-8")

    assert "TODO\\_RESULT" in summary_text
    assert "\\input{tables/table_bucket_ablation}" in summary_text
    assert "\\input{figures/fig_oracle_gap_waterfall}" in summary_text
    assert "analysis-only upper bounds" in summary_text
    assert "\\newcommand{\\PaperScaleEvidenceStatus}{TODO_RESULT}" in macros_text
    assert "table_bucket_ablation.tex" in manifest_text
    assert "Wrote report manifest" in completed.stdout
