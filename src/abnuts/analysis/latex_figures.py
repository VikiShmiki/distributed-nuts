def _escape_latex(value: str) -> str:
    return (
        value.replace("\\", "\\textbackslash{}")
        .replace("&", "\\&")
        .replace("%", "\\%")
        .replace("$", "\\$")
        .replace("#", "\\#")
        .replace("_", "\\_")
        .replace("{", "\\{")
        .replace("}", "\\}")
    )


def _short_oracle_gap_label(scheduler_label: str, bucket_size: int) -> str:
    label = scheduler_label.replace(" (analysis-only upper bound)", " upper")
    if bucket_size == 0:
        return label
    return f"{label} S={bucket_size}"


def _runtime_breakdown_label(method: str, predictor: str, bucket_size: int) -> str:
    if method == "bucketed":
        return f"{predictor} S={bucket_size}"
    return method
