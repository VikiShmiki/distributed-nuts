def write_runtime_breakdown_figure(
    summary: RuntimeBreakdownSummary,
    out_dir: str | Path,
    *,
    command: str,
) -> Path:
    """Write a stacked PGFPlots runtime component figure."""
    figure_dir = Path(out_dir) / "figures"
    figure_dir.mkdir(parents=True, exist_ok=True)
    source_path = figure_dir / "runtime_breakdown.csv"
    figure_path = figure_dir / "fig_runtime_breakdown.tex"
    _write_runtime_breakdown_csv(summary, source_path)

    labels = ", ".join(
        _escape_latex(_runtime_breakdown_label(row.method, row.predictor, row.bucket_size))
        for row in summary.rows
    )
    xticks = ", ".join(str(index + 1) for index, _row in enumerate(summary.rows))
    components = (
        ("Cold compile", "mean_cold_compile_seconds"),
        ("Planner", "mean_planner_seconds"),
        ("Executor", "mean_executor_seconds"),
        ("Gather", "mean_gather_seconds"),
        ("Scatter", "mean_scatter_seconds"),
        ("HVP", "mean_hvp_seconds"),
        ("Other warm", "mean_unattributed_seconds"),
    )
    lines = [
        f"% Generated by: {command}",
        f"% Source result file: {summary.source_csv}",
        f"% Source figure data: {source_path.name}",
        "\\begin{tikzpicture}",
        "\\begin{axis}[",
        "  ybar stacked,",
        "  xlabel={Run configuration},",
        "  ylabel={Seconds},",
        "  legend columns=2,",
        "  legend pos=north west,",
        "  grid=both,",
        "  width=0.88\\linewidth,",
        "  height=0.54\\linewidth,",
        f"  xtick={{{xticks}}},",
        f"  xticklabels={{{labels}}},",
        "  x tick label style={rotate=35, anchor=east},",
        "]",
    ]
    for label, attribute in components:
        coords = " ".join(
            f"({index + 1},{getattr(row, attribute):.6f})"
            for index, row in enumerate(summary.rows)
        )
        lines.extend(
            [
                f"\\addplot+ coordinates {{{coords}}};",
                f"\\addlegendentry{{{_escape_latex(label)}}}",
            ]
        )
    lines.extend(["\\end{axis}", "\\end{tikzpicture}", ""])
    figure_path.write_text("\n".join(lines), encoding="utf-8")
    return figure_path


def write_sbc_rank_histogram_figure(
    summary: SBCRankHistogramSummary,
    out_dir: str | Path,
    *,
    command: str,
) -> Path:
    """Write a PGFPlots SBC rank histogram figure."""
    figure_dir = Path(out_dir) / "figures"
    figure_dir.mkdir(parents=True, exist_ok=True)
    source_path = figure_dir / "sbc_rank_histogram.csv"
    figure_path = figure_dir / "fig_sbc_rank_histogram.tex"
    _write_sbc_rank_histogram_csv(summary, source_path)

    methods = tuple(dict.fromkeys(row.method for row in summary.rows))
    ranks = sorted({row.rank for row in summary.rows})
    xticks = ", ".join(str(rank) for rank in ranks)
    title = (
        "Tiny SBC smoke only; not paper evidence"
        if summary.is_smoke_only
        else "Simulation-based calibration ranks"
    )
    lines = [
        f"% Generated by: {command}",
        f"% Source result file: {summary.source_csv}",
        f"% Source figure data: {source_path.name}",
    ]
    if summary.is_smoke_only:
        lines.append("% Tiny SBC profile is smoke-only and not paper evidence.")
    lines.extend(
        [
            "\\begin{tikzpicture}",
            "\\begin{axis}[",
            "  ybar,",
            "  xlabel={Rank},",
            "  ylabel={Replicates},",
            "  legend pos=north east,",
            "  grid=both,",
            "  width=0.78\\linewidth,",
            "  height=0.50\\linewidth,",
            f"  xtick={{{xticks}}},",
            f"  title={{{_escape_latex(title)}}},",
            "]",
        ]
    )
    for method in methods:
        coords = " ".join(
            f"({row.rank},{row.count})" for row in summary.rows if row.method == method
        )
        lines.extend(
            [
                f"\\addplot+ coordinates {{{coords}}};",
                f"\\addlegendentry{{{_escape_latex(method)}}}",
            ]
        )
    lines.extend(["\\end{axis}", "\\end{tikzpicture}", ""])
    figure_path.write_text("\n".join(lines), encoding="utf-8")
    return figure_path


def _write_predictor_calibration_csv(
    summary: PredictorCalibrationSummary,
    source_path: Path,
) -> None:
    with source_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=[
                "scheduler_mode",
                "scheduler_label",
                "bucket_size",
                "is_analysis_upper_bound",
                "predicted_work",
                "realized_work",
                "abs_error",
                "is_summary_proxy",
            ],
            lineterminator="\n",
        )
        writer.writeheader()
        for row in summary.rows:
            writer.writerow(
                {
                    "scheduler_mode": row.scheduler_mode,
                    "scheduler_label": row.scheduler_label,
                    "bucket_size": row.bucket_size,
                    "is_analysis_upper_bound": row.is_analysis_upper_bound,
                    "predicted_work": f"{row.predicted_work:.8g}",
                    "realized_work": f"{row.realized_work:.8g}",
                    "abs_error": f"{row.abs_error:.8g}",
                    "is_summary_proxy": row.is_summary_proxy,
                }
            )


