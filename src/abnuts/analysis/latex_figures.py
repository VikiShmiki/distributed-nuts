def write_predictor_calibration_figure(
    summary: PredictorCalibrationSummary,
    out_dir: str | Path,
    *,
    command: str,
) -> Path:
    """Write a PGFPlots predictor calibration scatter figure."""
    figure_dir = Path(out_dir) / "figures"
    figure_dir.mkdir(parents=True, exist_ok=True)
    source_path = figure_dir / "predictor_calibration.csv"
    figure_path = figure_dir / "fig_predictor_calibration.tex"
    _write_predictor_calibration_csv(summary, source_path)

    series = tuple(dict.fromkeys(row.scheduler_label for row in summary.rows))
    max_axis_value = max(
        (max(row.predicted_work, row.realized_work) for row in summary.rows),
        default=1.0,
    )
    identity_max = max(1.0, max_axis_value)
    lines = [
        f"% Generated by: {command}",
        f"% Source result file: {summary.source_csv}",
        f"% Source figure data: {source_path.name}",
        "% oracle_current is an analysis-only upper bound, not a deployable scheduler.",
        "\\begin{tikzpicture}",
        "\\begin{axis}[",
        "  xlabel={Predicted work},",
        "  ylabel={Realized tree depth},",
        "  legend pos=north west,",
        "  grid=both,",
        "  width=0.78\\linewidth,",
        "  height=0.52\\linewidth,",
        "  title={Predictor calibration; oracle-current is analysis-only},",
        "]",
        "\\addplot+[gray, dashed, mark=none] coordinates "
        f"{{(0,0) ({identity_max:.6f},{identity_max:.6f})}};",
        "\\addlegendentry{ideal}",
    ]
    for label in series:
        coords = " ".join(
            f"({row.predicted_work:.6f},{row.realized_work:.6f})"
            for row in summary.rows
            if row.scheduler_label == label
        )
        if not coords:
            continue
        lines.extend(
            [
                f"\\addplot+[only marks] coordinates {{{coords}}};",
                f"\\addlegendentry{{{_escape_latex(_short_oracle_gap_label(label, 0))}}}",
            ]
        )
    lines.extend(["\\end{axis}", "\\end{tikzpicture}", ""])
    figure_path.write_text("\n".join(lines), encoding="utf-8")
    return figure_path


