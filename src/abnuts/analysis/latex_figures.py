def write_speedup_vs_bucket_size_figure(
    summary: AblationSummary,
    out_dir: str | Path,
    *,
    command: str,
) -> Path:
    """Write a PGFPlots figure for speedup versus bucket size."""
    figure_dir = Path(out_dir) / "figures"
    figure_dir.mkdir(parents=True, exist_ok=True)
    figure_path = figure_dir / "fig_speedup_vs_bucket_size.tex"
    predictors = tuple(dict.fromkeys(row.predictor for row in summary.rows))
    lines = [
        f"% Generated by: {command}",
        f"% Source result file: {summary.source_csv}",
        "\\begin{tikzpicture}",
        "\\begin{axis}[",
        "  xlabel={Bucket size},",
        "  ylabel={Warm speedup},",
        "  legend pos=north west,",
        "  grid=both,",
        "  width=0.78\\linewidth,",
        "  height=0.48\\linewidth,",
        "]",
    ]
    for predictor in predictors:
        coords = " ".join(
            f"({row.bucket_size},{row.mean_speedup:.6f})"
            for row in summary.rows
            if row.predictor == predictor
        )
        lines.extend(
            [
                f"\\addplot+[mark=*] coordinates {{{coords}}};",
                f"\\addlegendentry{{{_escape_latex(predictor)}}}",
            ]
        )
    lines.extend(
        [
            "\\end{axis}",
            "\\end{tikzpicture}",
            "",
        ]
    )
    figure_path.write_text("\n".join(lines), encoding="utf-8")
    return figure_path


