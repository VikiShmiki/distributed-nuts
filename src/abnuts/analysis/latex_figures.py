        "\\begin{axis}[",
        "  ybar,",
        "  xlabel={Scheduler},",
        "  ylabel={Warm speedup},",
        "  ymin=0,",
        "  grid=both,",
        "  width=0.88\\linewidth,",
        "  height=0.50\\linewidth,",
        f"  xtick={{{', '.join(str(index + 1) for index, _ in enumerate(summary.rows))}}},",
        f"  xticklabels={{{xticklabels}}},",
        "  x tick label style={rotate=35, anchor=east},",
        "  title={Oracle-current is an analysis-only upper bound},",
