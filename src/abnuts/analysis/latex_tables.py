def write_sensitivity_summary(
    summary: SensitivitySummary,
    out_dir: str | Path,
    *,
    command: str,
) -> Path:
    """Write a short includeable LaTeX sensitivity summary."""
    out_path = Path(out_dir) / "sensitivity_summary.tex"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    worst = summary.worst_row
    lines = [
        f"% Generated by: {command}",
        f"% Source result root: {summary.source_root}",
        f"% {summary.evidence_note}",
        "\\paragraph{Sensitivity and worst-group evidence.}",
        _escape_latex(summary.evidence_note),
        "",
        (
            "The lowest observed worst-group mean speedup is "
            f"{worst.mean_speedup:.3f} for {_escape_latex(worst.stratum)} = "
            f"{_escape_latex(worst.group)} across {worst.runs} rows. "
            f"The worst single-row speedup in that group is {worst.worst_speedup:.3f}."
        ),
        "",
        (
            "Quality guardrails over included speedup rows report "
            f"{summary.total_divergences} total divergences and maximum realized tree depth "
            f"{summary.max_tree_depth}."
        ),
        "",
        (
            "Posterior-diagnostic coverage: "
            f"{summary.diagnostic_row_count} rows from {summary.diagnostic_file_count} "
            "diagnostics files; max $\\widehat{R}$ = "
            f"{_format_optional_float(summary.max_r_hat, 3)}, min bulk ESS = "
            f"{_format_optional_float(summary.min_bulk_ess, 1)}, min tail ESS = "
            f"{_format_optional_float(summary.min_tail_ess, 1)}."
        ),
        "",
        "\\input{tables/table_sensitivity_worst_groups}",
        "\\input{tables/table_sensitivity_coverage}",
        "",
    ]
    out_path.write_text("\n".join(lines), encoding="utf-8")
    return out_path


def _history_speedup(summary: AblationSummary) -> float:
    history_rows = [row for row in summary.rows if row.predictor == "history"]
    if not history_rows:
        return 0.0
    return max(row.mean_speedup for row in history_rows)


def _best_config_text(row: AblationRow | ChainScalingRow | DimensionScalingRow) -> str:
    predictor = _escape_latex(row.predictor)
    if isinstance(row, ChainScalingRow):
        return f"{predictor}, {row.num_chains} chains, bucket size {row.bucket_size}"
    if isinstance(row, DimensionScalingRow):
        return f"{predictor}, D={row.dimension}, bucket size {row.bucket_size}"
    return f"{predictor}, bucket size {row.bucket_size}"


def _escape_latex(value: str) -> str:
    return (
        value.replace("\\", "\\textbackslash{}")
        .replace("&", "\\&")
        .replace("%", "\\%")
        .replace("$", "\\$")
        .replace("#", "\\#")
        .replace("_", "\\_")
        .replace("{", "\\{")
        .replace("}", "\\}")
    )


def _format_bucket_size(bucket_size: int) -> str:
    if bucket_size == 0:
        return "--"
    return str(bucket_size)


def _format_float(value: float, digits: int) -> str:
    if value != value:
        return "--"
    return f"{value:.{digits}f}"


def _format_optional_float(value: float | None, digits: int) -> str:
    if value is None:
        return "--"
    return _format_float(value, digits)
