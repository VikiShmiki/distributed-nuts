def write_sensitivity_worst_group_table(
    summary: SensitivitySummary,
    out_dir: str | Path,
    *,
    command: str,
) -> Path:
    """Write the sensitivity worst-group table as LaTeX source."""
    table_dir = Path(out_dir) / "tables"
    table_dir.mkdir(parents=True, exist_ok=True)
    table_path = table_dir / "table_sensitivity_worst_groups.tex"
    evidence = "Smoke-only evidence; not paper-scale claims." if summary.is_smoke_only else (
        "Paper-scale candidate evidence; check uncertainty before claiming."
    )
    lines = [
        f"% Generated by: {command}",
        f"% Source result root: {summary.source_root}",
        f"% {summary.evidence_note}",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Sensitivity worst-group report. " + _escape_latex(evidence) + "}",
        "\\label{tab:sensitivity-worst-groups}",
        "\\begin{tabular}{llrrrrrrr}",
        "\\hline",
        "Stratum & Worst group & Sources & Runs & Mean speedup & Worst speedup & "
        "Padding & Div. & Max depth \\\\",
        "\\hline",
    ]
    for row in summary.rows:
        group = row.group
        if row.analysis_upper_bound_runs:
            group = f"{group} ({row.analysis_upper_bound_runs} upper-bound rows)"
        lines.append(
            f"{_escape_latex(row.stratum)} & {_escape_latex(group)} & "
            f"{row.source_count} & {row.runs} & {row.mean_speedup:.3f} & "
            f"{row.worst_speedup:.3f} & {row.mean_padding_ratio:.3f} & "
            f"{row.total_divergences} & {row.max_tree_depth} \\\\"
        )
    lines.extend(
        [
            "\\hline",
            "\\end{tabular}",
            "\\end{table}",
            "",
        ]
    )
    table_path.write_text("\n".join(lines), encoding="utf-8")
    return table_path


