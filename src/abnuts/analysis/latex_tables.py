def write_bucket_ablation_table(
    summary: AblationSummary,
    out_dir: str | Path,
    *,
    command: str,
) -> Path:
    """Write the funnel bucket-ablation table as LaTeX source."""
    table_dir = Path(out_dir) / "tables"
    table_dir.mkdir(parents=True, exist_ok=True)
    table_path = table_dir / "table_bucket_ablation.tex"
    lines = [
        f"% Generated by: {command}",
        f"% Source result file: {summary.source_csv}",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Funnel bucket-size and predictor ablation.}",
        "\\label{tab:bucket-ablation}",
        "\\begin{tabular}{lrrrrrr}",
        "\\hline",
        "Predictor & Bucket & Runs & $t_{\\mathrm{mono}}$ & "
        "$t_{\\mathrm{bucket}}$ & Speedup & Padding \\\\",
        "\\hline",
    ]
    for row in summary.rows:
        lines.append(
            f"{_escape_latex(row.predictor)} & {row.bucket_size} & {row.runs} & "
            f"{row.mean_t_mono:.4f} & {row.mean_t_bucket:.4f} & "
            f"{row.mean_speedup:.3f} & {row.mean_padding_ratio:.3f} \\\\"
        )
    lines.extend(
        [
            "\\hline",
            "\\end{tabular}",
            "\\end{table}",
            "",
        ]
    )
    table_path.write_text("\n".join(lines), encoding="utf-8")
    return table_path


def write_result_macros(
    summary: AblationSummary | ChainScalingSummary | DimensionScalingSummary,
    out_dir: str | Path,
    *,
    command: str,
) -> Path:
    """Write reusable LaTeX macros for a benchmark summary."""
    macros_dir = Path(out_dir) / "macros"
    macros_dir.mkdir(parents=True, exist_ok=True)
    macros_path = macros_dir / "result_macros.tex"
    best = summary.best_row
    lines = [
        f"% Generated by: {command}",
        f"% Source result file: {summary.source_csv}",
        f"\\newcommand{{\\BestWarmSpeedup}}{{{best.mean_speedup:.3f}}}",
        f"\\newcommand{{\\BestWarmSpeedupConfig}}{{{_best_config_text(best)}}}",
    ]
    if isinstance(summary, AblationSummary):
        lines.append(
            f"\\newcommand{{\\FunnelHistorySpeedupCtiny}}{{{_history_speedup(summary):.3f}}}"
        )
    if isinstance(summary, ChainScalingSummary):
        lines.append(
            f"\\newcommand{{\\ChainScalingBestChains}}{{{summary.best_row.num_chains}}}"
        )
        lines.append(
            f"\\newcommand{{\\ChainScalingBestSpeedup}}{{{summary.best_row.mean_speedup:.3f}}}"
        )
    if isinstance(summary, DimensionScalingSummary):
        lines.append(
            f"\\newcommand{{\\DimensionScalingBestDimension}}{{{summary.best_row.dimension}}}"
        )
        lines.append(
            "\\newcommand{\\DimensionScalingBestSpeedup}"
            f"{{{summary.best_row.mean_speedup:.3f}}}"
        )
    lines.append("")
    macros_path.write_text("\n".join(lines), encoding="utf-8")
    return macros_path


